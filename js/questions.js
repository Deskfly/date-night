// Flat list with stable ids, e.g. "us-07", so "seen" survives app updates.
export const QUESTIONS = Object.entries(RAW).flatMap(([cat, list]) =>
  list.map((text, i) => ({ id: `${cat}-${String(i + 1).padStart(2, '0')}`, cat, text })));

export function catInfo(id) {
  return Q_CATS.find((c) => c.id === id) || Q_CATS[0];
}

// Picks a random question in the category that hasn't been seen yet.
// When every question in the category has been seen, starts the round over.
export function nextQuestion(cat, seen, avoidId) {
  const pool = QUESTIONS.filter((q) => cat === 'all' || q.cat === cat);
  let fresh = pool.filter((q) => !seen.includes(q.id) && q.id !== avoidId);
  let reset = false;
  if (!fresh.length) {
    fresh = pool.filter((q) => q.id !== avoidId);
    reset = true;
  }
  return { q: fresh[Math.floor(Math.random() * fresh.length)], reset, left: fresh.length - 1, total: pool.length };
}
